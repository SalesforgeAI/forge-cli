import { readFile, writeFile } from "node:fs/promises";
import { publicApiSources, readPublicApiDocument, publicDocument } from "./public-api-sources.mjs";

const flags = process.argv.slice(2);
if (flags.some((flag) => flag !== "--check")) throw new Error("Usage: node scripts/sync-public-api.mjs [--check]");

/** Resolve request schemas and remove generator-only OpenAPI metadata. */
function resolveSchema(schema, document, seen = new Set()) {
  if (schema.$ref) {
    if (seen.has(schema.$ref)) throw new Error(`Recursive request schema: ${schema.$ref}`);
    const referenced = schema.$ref.split("/").slice(1).reduce((value, key) => value[key], document);
    return resolveSchema(referenced, document, new Set([...seen, schema.$ref]));
  }
  // Swag emits an unconstrained object alongside the real request schema.
  const reference = schema.oneOf?.find((entry) => entry.$ref);
  if (reference) return resolveSchema(reference, document, seen);
  const result = {};
  for (const part of schema.allOf ?? []) {
    const resolved = resolveSchema(part, document, seen);
    const properties = { ...result.properties, ...resolved.properties };
    const required = [...new Set([...(result.required ?? []), ...(resolved.required ?? [])])];
    Object.assign(result, resolved);
    if (Object.keys(properties).length) result.properties = properties;
    if (required.length) result.required = required;
  }
  for (const key of ["type", "description", "enum", "required", "minimum", "maximum", "minLength", "maxLength", "minItems", "maxItems"]) {
    if (schema[key] !== undefined) result[key] = schema[key];
  }
  if (schema.properties) result.properties = Object.fromEntries(Object.entries(schema.properties).map(([key, value]) => [key, resolveSchema(value, document, seen)]));
  if (schema.items) result.items = resolveSchema(schema.items, document, seen);
  if (schema.additionalProperties !== undefined) result.additionalProperties = typeof schema.additionalProperties === "boolean" ? schema.additionalProperties : resolveSchema(schema.additionalProperties, document, seen);
  return result;
}

/** Normalize OpenAPI 3 and Swagger 2 operations into the shared request contract. */
function collectContracts(service, document) {
  const contracts = {};
  for (const [path, methods] of Object.entries(document.paths)) {
    for (const [method, operation] of Object.entries(methods)) {
      if (!["get", "post", "put", "patch", "delete"].includes(method)) continue;
      const parameters = operation.parameters ?? [];
      const body = operation.requestBody?.content?.["application/json"]?.schema ?? parameters.find((p) => p.in === "body")?.schema;
      const resolvedBody = body ? resolveSchema(body, document) : undefined;
      if (document.swagger && resolvedBody?.properties) {
        // Swagger includes Go fields bound exclusively from route parameters in body schemas.
        for (const p of parameters.filter((p) => p.in === "path")) {
          delete resolvedBody.properties[p.name];
          if (resolvedBody.required) resolvedBody.required = resolvedBody.required.filter((name) => name !== p.name);
        }
      }
      contracts[`${service} ${method.toUpperCase()} ${path}`] = {
        description: operation.description || operation.summary,
        parameters: parameters.filter((p) => p.in !== "body").map(({ name, in: location, required, description, schema, ...inline }) => ({
          name, location, required: Boolean(required), schema: { ...resolveSchema(schema ?? inline, document), ...(description ? { description } : {}) },
        })),
        ...(resolvedBody ? { body: resolvedBody } : {}),
      };
    }
  }
  return contracts;
}

/** Write a deterministic snapshot, or fail when its upstream contracts have drifted. */
async function saveContracts(contracts, relativePath, importPath, exportName) {
  const output = `// Generated by scripts/sync-public-api.mjs from public API documents.\n// Regenerate with npm run sync:public-api; review contract changes before committing.\nimport type { PublicApiContract } from "${importPath}";\n\nexport const ${exportName}: Record<string, PublicApiContract> = ${JSON.stringify(contracts, null, 2)};\n`;
  const destination = new URL(relativePath, import.meta.url);
  if (process.argv.includes("--check")) {
    if (await readFile(destination, "utf8") !== output) throw new Error(`Public API contracts changed: ${relativePath}. Run npm run sync:public-api and review coverage.`);
    console.log(`Verified ${Object.keys(contracts).length} public API operations in ${relativePath}.`);
  } else {
    await writeFile(destination, output);
    console.log(`Synced ${Object.keys(contracts).length} public API operations in ${relativePath}.`);
  }
}

const contracts = {};
const services = Object.keys(publicApiSources);
const documents = await Promise.allSettled(services.map((service) => readPublicApiDocument(service)));
const failures = documents.filter((result) => result.status === "rejected");
if (failures.length) throw new AggregateError(failures.map((result) => result.reason), "Could not read all public API schemas; snapshot unchanged");
for (const [index, service] of services.entries()) {
  const source = documents[index].value;
  const document = ["salesforge", "multichannel"].includes(service) ? source : publicDocument(service, source);
  Object.assign(contracts, collectContracts(service, document));
}
await saveContracts(contracts, "../src/commands/contracts.ts", "./endpoint.js", "publicApiContracts");
